import assert from 'node:assert/strict';
import fs from 'node:fs';
import {AAD_VIEW_COLOURS,AAD_WINDOW_COLOURS,AAD_VIEW_COLOUR_SOURCES,aadContrastRatio} from '../../public/assets/js/aad-view-colours.mjs';
const read=p=>JSON.parse(fs.readFileSync(p,'utf8'));
const review=read('public/data/projects/ashok-adhikari/window-visibility-review-20261112.json');
const model=read('public/data/projects/ashok-adhikari/aad-building-v3-3-review.json');
const ff=read('public/data/projects/ashok-adhikari/aad-ff-model-v3-3-review.json');
const source=fs.readFileSync('cad/aad/multistorey/main.js','utf8');
const plan=fs.readFileSync('public/assets/js/aad-dimensioned-plan.mjs','utf8');
const html=fs.readFileSync('cad/aad/multistorey/index.html','utf8');
assert.equal(review.edition,'v3.3');
assert.equal(review.scope,'PRESENTATION_ONLY');
assert.equal(review.governance.release,'ashok-v3.3.0-window-visibility-review.1');
assert.equal(AAD_WINDOW_COLOURS.planStroke,review.window.approvedVisualConvention.svgStroke);
assert.equal(AAD_WINDOW_COLOURS.planPane,review.window.approvedVisualConvention.svgPane);
assert.equal(AAD_WINDOW_COLOURS.frame3D,review.window.approvedVisualConvention.threeDimensionalFrame);
assert.equal(AAD_WINDOW_COLOURS.glass3D,review.window.approvedVisualConvention.threeDimensionalGlazing);
assert.equal(AAD_WINDOW_COLOURS.glassOpacity,review.window.approvedVisualConvention.glazingOpacity);
assert.ok(aadContrastRatio(AAD_WINDOW_COLOURS.planStroke,'#FAF8EF')>=7,'Window plan must comfortably exceed WCAG 3:1 graphic contrast');
assert.ok(aadContrastRatio('#62A2AD','#FAF8EF')<3,'Check original low-contrast window stroke baseline');
assert.equal(review.categoryAudit.filter(c=>c.action.startsWith('RECOLOUR')).map(c=>c.kind).join(','),'window');
for(const [kind,value] of Object.entries({wall:'#4D7889',door:'#C28D72',column:'#40997D',beam:'#CEA365',slab:'#96BBA8',stair:'#9386BB'}))
 assert.equal(AAD_VIEW_COLOURS[kind],value,'Existing '+kind+' colour must not change');
assert.match(source,/AAD_WINDOW_COLOURS\.glass3D/);
assert.match(source,/AAD_WINDOW_COLOURS\.glassOpacity/);
assert.match(source,/AAD_WINDOW_COLOURS\.frame3D/);
assert.match(source,/data-aad-window-pane/);
assert.match(source,/getViewColourProof/);
assert.match(plan,/AAD_WINDOW_COLOURS\.planStroke/);
assert.match(html,/data-aad-legend-kind="window"/);
assert.match(html,/aad-window-pane/);
assert.equal(model.release.version,'v3-3-review');
assert.equal(model.restrictions.issueForConstruction,false);
assert.equal(ff.floorGraph.openings.find(o=>o.id==='FF-W009-C4-C2-OWNER-20261112')?.width,2.1);
assert.equal(ff.floorGraph.openings.find(o=>o.id==='FF-D-LOUNGE-MAIN')?.offset,.55);
assert.equal(model.presentation.columnAxisGrid.letterAxes.find(x=>x.label==='B')?.xMm,3600);
assert.ok(AAD_VIEW_COLOUR_SOURCES.some(s=>s.includes('w3.org')));
assert.ok(AAD_VIEW_COLOUR_SOURCES.some(s=>s.includes('buildingsmart.org')));
console.log('ASHOK_WINDOW_PALETTE_SEMANTICS_AND_SOURCE_NON_MUTATION_PASS',JSON.stringify({window2D:AAD_WINDOW_COLOURS.planStroke,contrast:Math.round(aadContrastRatio(AAD_WINDOW_COLOURS.planStroke,'#FAF8EF')*100)/100,windowGlass:AAD_WINDOW_COLOURS.glass3D,otherCategoriesUnchanged:true}));
