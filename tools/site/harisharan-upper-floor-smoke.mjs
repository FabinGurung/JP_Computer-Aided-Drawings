import assert from 'node:assert/strict';
import fs from 'node:fs';
import {computeUpperFloorReview,readBars,steelMassPerMetre,csv,EXPORT_FIELDS} from '../../public/assets/js/harisharan-upper-floor-source.mjs';
const raw=JSON.parse(fs.readFileSync('public/data/projects/harisharan-adhikari/upper-floor-source-r000001.json','utf8'));
const base=JSON.parse(fs.readFileSync('public/data/projects/harisharan-adhikari/takeoff.json','utf8'));
assert.equal(raw.basis.structuralReport.sha256,base.sources.find(s=>s.id==='HAR-SRC-RPT-001').sha256);
assert.equal(raw.basis.architectural.sha256,base.sources.find(s=>s.id==='HAR-SRC-ARC-001').sha256);
assert.equal(raw.basis.structural.sha256,base.sources.find(s=>s.id==='HAR-SRC-STR-001').sha256);
assert.equal(raw.records.length,18);
assert.deepEqual(raw.architecturalFloorIdentifiers.map(x=>x.id),['ground','first','second','third','fourth']);
assert.equal(raw.unresolved.length,6);
const r=computeUpperFloorReview(raw);
assert.equal(r.approval,false);assert.equal(r.issueForConstruction,false);
assert.equal(r.entries.length,90);assert.equal(r.perFloor.length,5);
assert.deepEqual(r.perFloor.map(x=>x.reportRows),[18,18,18,18,18]);
assert.ok(r.perFloor.every(x=>x.approvedSteelKg===null&&x.approvedConcreteM3===null));
assert.ok(r.entries.every(x=>x.tieSteelKg===null&&x.lapSteelKg===null&&x.approvedBbs===null));
assert.equal(r.entries[0].barNotation,'12#-20 mm');
assert.equal(r.entries.find(x=>x.grid==='B4'&&x.floorId==='ground').barNotation,'6#-25mm & 6#-20 mm');
assert.equal(r.entries.find(x=>x.grid==='A2'&&x.floorId==='first').barNotation,'8#-20mm & 4#-16 mm');
assert.equal(r.entries.find(x=>x.grid==='A1'&&x.floorId==='third').barNotation,r.entries.find(x=>x.grid==='A1'&&x.floorId==='fourth').barNotation);
assert.equal(readBars('6#-25mm & 6#-20 mm').length,2);
assert.throws(()=>readBars('12#-20mm or guessed'),/Unrecognized/);
assert.ok(Math.abs(steelMassPerMetre(readBars('12#-20 mm')) - 12*Math.PI/4*(.02**2)*7850)<.00001);
assert.ok(r.totals.scenarioGrossColumnPrismsM3>0);
assert.ok(r.entries.every(x=>x.grossConcreteM3===.6075));
const shorter=computeUpperFloorReview(raw,{heightScenarioM:2.8});
assert.ok(shorter.totals.scenarioLongitudinalKg<r.totals.scenarioLongitudinalKg);
assert.ok(shorter.totals.scenarioGrossColumnPrismsM3<r.totals.scenarioGrossColumnPrismsM3);
assert.throws(()=>computeUpperFloorReview(raw,{heightScenarioM:5.5}),/bounded/);
assert.equal(r.totals.approvedSteelKg,null);
assert.equal(r.totals.approvedConcreteM3,null);
assert.equal(r.totals.approvedProcurementKg,null);
assert.equal(raw.reportBeamFamilies.length,2);
assert.ok(raw.reportBeamFamilies.every(x=>x.status.includes('NOT_MAPPED')));
assert.match(raw.unresolved[0].topic,/G\+5/);
const text=csv(r.entries,EXPORT_FIELDS);
assert.equal(text.split('\r\n').length,92);
assert.match(text,/NOT_FOR_CONSTRUCTION/);
assert.match(text,/UF-FOURTH-B4/);
assert.ok(!/APPROVED_FOR_CONSTRUCTION/.test(text));
assert.ok(fs.existsSync('public/projects/harisharan-adhikari/upper-floors/index.html'));
const html=fs.readFileSync('public/projects/harisharan-adhikari/upper-floors/index.html','utf8');
assert.match(html,/NOT FOR CONSTRUCTION/);
assert.match(html,/id="plan"/);
assert.match(html,/id="elevation"/);
assert.match(html,/R3 · Upper-floor/);
console.log('HARISHARAN_UPPER_FLOOR_R3_STATIC_PASS sourceRows=18 floorCategories=5 comparativeEntries=90 structuralApproval=false');
