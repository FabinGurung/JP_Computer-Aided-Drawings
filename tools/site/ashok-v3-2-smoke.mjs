import assert from 'node:assert/strict';
import fs from 'node:fs';
import {createAADWorkspace} from '../../public/assets/js/aad-unified-workspace.mjs';
const dir='public/data/projects/ashok-adhikari/';
const read=n=>JSON.parse(fs.readFileSync(dir+n,'utf8'));
const manifest=read('aad-building-v3-2-review.json'),gf=read('aad-gf-model-v3-grid-review.json'),old=read('aad-ff-model-v3-review.json'),ff=read('aad-ff-model-v3-2-review.json'),ledger=read('coordination-20261108.json');
assert.equal(manifest.release.version,'v3-2-review');
assert.equal(manifest.release.previous,'v3-grid-review');
assert.deepEqual(manifest.levels.map(l=>l.model),['aad-gf-model-v3-grid-review.json','aad-ff-model-v3-2-review.json']);
assert.deepEqual(manifest.presentation.coordinateGrid.sharedByLevels,['gf','ff']);
assert.equal(manifest.presentation.coordinateGrid.baseCellMm,100);
assert.equal(manifest.representation,'ARCHITECTURAL_REVIEW_ONLY');
assert.equal(manifest.restrictions.engineeringApproval,'HOLD');
assert.equal(manifest.restrictions.issueForConstruction,false);
const nodes=d=>Object.fromEntries(d.floorGraph.nodes.map(n=>[n.id,n]));
const n0=nodes(old),n1=nodes(ff),ng=nodes(gf);
const edge=(d,id)=>{const w=d.floorGraph.walls.find(w=>w.id===id);assert.ok(w,id);const n=nodes(d);return[n[w.a],n[w.b]];};
for(const id of ['FF-N014','FF-N016','FF-N017','FF-N018']){assert.equal(n0[id].x,3.3);assert.equal(n1[id].x,3.6);}
for(const id of ['GF-BED-KITCHEN','GF-BATH-LOUNGE-V3','GF-HALL-LOW-1'])assert.deepEqual(edge(gf,id).map(p=>p.x),[3.6,3.6]);
for(const id of ['FF-ROOM-LOUNGE-1','FF-ROOM-LOUNGE-2','FF-ROOM-LOUNGE-3'])assert.deepEqual(edge(ff,id).map(p=>p.x),[3.6,3.6]);
for(const id of ['FF-EXT-02-1','FF-EXT-02-2','FF-EXT-03','FF-EXT-04-1'])assert.deepEqual(edge(ff,id),edge(old,id),'Exterior / staircase must remain identical');
assert.deepEqual(edge(gf,'GF-EXT-02-1').map(p=>p.x),edge(ff,'FF-EXT-02-1').map(p=>p.x));
const ops=d=>Object.fromEntries(d.floorGraph.openings.map(o=>[o.id,o]));
const o0=ops(old),o1=ops(ff);
assert.equal(ff.floorGraph.openings.length,old.floorGraph.openings.length);
assert.deepEqual(Object.keys(o0).sort(),Object.keys(o1).sort());
assert.equal(3300+o0['FF-D-LOUNGE-MAIN'].offset*1000,5800);
assert.equal(3600+o1['FF-D-LOUNGE-MAIN'].offset*1000,5800);
assert.equal(o1['FF-W008-BED2-STAIR-V3'].offset,1.2925);
const rear=edge(ff,'FF-STAIR-REAR-1');
assert.ok(Math.abs((rear[1].x-rear[0].x-o1['FF-W008-BED2-STAIR-V3'].width)/2-o1['FF-W008-BED2-STAIR-V3'].offset)<1e-9);
assert.equal(ff.floorGraph.openings.filter(o=>o.wallId==='FF-STAIR-REAR-1').length,1);
const before=Object.fromEntries(old.roomEnvelopes.map(r=>[r.id,r])),after=Object.fromEntries(ff.roomEnvelopes.map(r=>[r.id,r]));
const a=r=>(r.bbox[2]-r.bbox[0])*(r.bbox[3]-r.bbox[1])/1e6;
const delta=id=>+(a(after[id])-a(before[id])).toFixed(3);
for(const [id,expected] of [['FF-WIR',.66],['FF-BATH',.525],['FF-BED2',1.035],['FF-LOUNGE',-2.22]])assert.equal(delta(id),expected);
assert.ok(Math.abs(Object.keys(before).reduce((sum,id)=>sum+delta(id),0))<1e-9,'Nominal area conservation must tolerate binary floating-point residue');
assert.equal(ledger.alignment.overlapMm,7400);
assert.equal(ledger.alignment.stairOffsetFromPartitionMm,575);
assert.equal(ledger.independentLoadPathReview.transferLoads,null);
assert.equal(ledger.independentStairReview.finishedHeadroomMm,null);
assert.ok(manifest.reviewHolds.some(h=>h.code==='20261108_STRUCTURAL_LOAD_PATH'));
const assembled=createAADWorkspace(manifest,{gf,ff}).snapshot().assembly;
assert.ok(assembled.elements.some(e=>e.level==='gf'));
assert.ok(assembled.elements.some(e=>e.level==='ff'));
assert.ok(assembled.diagnostics.some(d=>d.code==='20261108_STRUCTURAL_LOAD_PATH'));
console.log('ASHOK_V3_2_SHARED_GF_FF_GRID_HOLD_AND_COORDINATION_PASS');
