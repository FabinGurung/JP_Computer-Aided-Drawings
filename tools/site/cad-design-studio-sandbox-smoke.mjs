/** Drawing sandbox: independent synthetic source, real AAD topology and 3D assembly. */
import assert from "node:assert/strict";
import fs from "node:fs";
import {assembleBuilding,verifyAssembly} from "../../public/assets/js/aad-building-core.mjs";
import {createAADWorkspace} from "../../public/assets/js/aad-unified-workspace.mjs";
const root="public/data/projects/design-studio-sandbox/";
const manifest=JSON.parse(fs.readFileSync(root+"aad-building-v1.json","utf8"));
const gf=JSON.parse(fs.readFileSync(root+"drawing-floor.json","utf8"));
const ff=JSON.parse(fs.readFileSync(root+"upper-floor.json","utf8"));
assert.equal(manifest.projectId,"AAD-SANDBOX-001");
assert.equal(manifest.representation,"ARCHITECTURAL_REVIEW_ONLY");
assert.equal(manifest.restrictions.issueForConstruction,false);
assert(!JSON.stringify(manifest).includes("PRJ-000007"));
const models={gf,ff},initial=assembleBuilding(manifest,models);
assert.equal(initial.area.model,96);
assert.equal(initial.area.source,96);
assert.equal(verifyAssembly(initial).valid,true);
assert.equal(initial.elements.filter(e=>e.kind==="column"||e.kind==="beam"||e.kind==="footing").length,0);
const before=initial.elements.filter(e=>e.kind==="wall").length;
assert(before>=8);
const w=createAADWorkspace(manifest,models);
const result=w.topology("gf","addWall",{start:{x:2,z:3},end:{x:6,z:3},thickness:.15});
assert(result.result.ids.length>0);
assert(w.snapshot().assembly.elements.filter(e=>e.kind==="wall").length>before);
assert.equal(w.snapshot().assembly.elements.filter(e=>e.kind==="column"||e.kind==="beam"||e.kind==="footing").length,0);
assert.equal(w.snapshot().assembly.manifest.restrictions.issueForConstruction,false);
assert.equal(gf.floorGraph.walls.length,4,"source fixture must be unchanged by edits");
const landing=fs.readFileSync("cad/aad/index.html","utf8");
assert(landing.includes("design-studio-sandbox/aad-building-v1.json")&&landing.includes('"sandbox","1"'),"general studio must use synthetic sandbox");
assert(!landing.includes("narayani-parajuli/aad-building-v1.json"),"general Design Studio must NOT default to Narayani");
assert(landing.includes("id=\"ds-editor\""),"accessible real editor iframe missing");
const app=fs.readFileSync("cad/aad/multistorey/main.js","utf8");
assert(app.includes('params.get("sandbox")==="1"')&&app.includes("setDrawMode(true)")&&app.includes('pointerdown'),'sandbox must enable pointer creation');
assert(app.includes('new DOMPoint(event.clientX,event.clientY)'),'drawing must map actual pointer coordinates');
const projects=fs.readFileSync("public/projects/index.html","utf8");
assert(!projects.includes("PRJ-000029"),"unverified/wrong Ramachandra project ID must not be shown");
console.log("AAD_DRAWING_SANDBOX_STATIC_PASS",JSON.stringify({levels:2,area:initial.area.model,originalWalls:before,createdWallCount:result.result.ids.length,noRealSourceData:true}));
