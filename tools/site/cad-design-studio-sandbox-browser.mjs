/** Real drawing acceptance: synthetic source, pointer wall, synchronized 3D, touch. */
import assert from "node:assert/strict";
import {chromium} from "playwright";
const root=process.env.CAD_SITE_URL||"http://127.0.0.1:5191/JP_Computer-Aided-Drawings/";
const base=new URL("cad/aad/",root).href;
const browser=await chromium.launch({headless:true,args:["--no-sandbox","--use-gl=angle","--use-angle=swiftshader"]});
const waitForWalls=async(page,n)=>page.waitForFunction(count=>{
 const frame=document.getElementById("ds-editor");
 return (frame?.contentWindow?.AADStudio?.getDraft()?.models?.gf?.floorGraph?.walls?.length||0)>=count;
},n,{timeout:25000});
const countWalls=async page=>page.locator("#ds-editor").evaluate(f=>f.contentWindow.AADStudio.getDraft().models.gf.floorGraph.walls.length);
const point=async(page,x,z)=>page.locator("#ds-editor").evaluate((frame,args)=>{
 const svg=frame.contentDocument.querySelector("#viewer2d"),r=svg.getBoundingClientRect();
 const pt=new frame.contentWindow.DOMPoint(args.x,args.z).matrixTransform(svg.getScreenCTM());
 return {x:pt.x-r.x,y:pt.y-r.y,outerX:frame.getBoundingClientRect().x+pt.x,outerY:frame.getBoundingClientRect().y+pt.y};
},{x,z});
try{
 const page=await browser.newPage({viewport:{width:1400,height:900},acceptDownloads:true});
 let errors=[];page.on("pageerror",e=>errors.push(e.message));
 const response=await page.goto(base,{waitUntil:"networkidle",timeout:75000});
 assert(response?.ok(),"Design Studio route must exist");
 assert.equal(await page.locator("#ds-editor").count(),1);
 const editor=page.frameLocator("#ds-editor");
 await editor.locator("#viewer2d").waitFor({state:"visible",timeout:60000});
 await page.waitForFunction(()=>document.getElementById("ds-editor")?.contentWindow?.AADStudio?.getSnapshot()?.assembly,{timeout:60000});
 assert.equal(await editor.locator("#aad-storey").inputValue(),"gf");
 assert.equal(await editor.locator("#aad-sandbox-draw").getAttribute("aria-pressed"),"true");
 assert(await editor.locator("#viewer3d canvas").count()===1,"shared 3D renderer must be available in desktop QA");
 const initial=await countWalls(page);
 assert.equal(initial,4);
 await editor.locator("#viewer2d").scrollIntoViewIfNeeded();
 const first=await point(page,2,3),last=await point(page,6,3);
 const canvasRect=await editor.locator("#viewer2d").boundingBox();
 console.log("CAD_SANDBOX_MOUSE_POINTER",JSON.stringify({first,last,canvasRect,viewport:{width:1400,height:900}}));
 assert(first.outerX>0&&first.outerX<1400&&first.outerY>0&&first.outerY<900,"draw start must be inside viewport");
 assert(last.outerX>0&&last.outerX<1400&&last.outerY>0&&last.outerY<900,"draw end must be inside viewport");
 await page.mouse.move(first.outerX,first.outerY);
 await page.mouse.down();
 await page.mouse.move(last.outerX,last.outerY,{steps:12});
 await page.mouse.up();
 await waitForWalls(page,initial+1);
 const afterDrag=await countWalls(page);
 assert(afterDrag>initial,"mouse drag must create a new wall");
 assert.equal(await editor.locator("#aad-sandbox-draw").getAttribute("aria-pressed"),"false");
 const assembly=await page.locator("#ds-editor").evaluate(f=>f.contentWindow.AADStudio.getSnapshot().assembly);
 assert.equal(assembly.elements.filter(e=>e.kind==="column"||e.kind==="beam"||e.kind==="footing").length,0);
 assert.equal(assembly.manifest.projectId,"AAD-SANDBOX-001");
 assert.equal(assembly.manifest.restrictions.issueForConstruction,false);
 assert.equal(assembly.elements.filter(e=>e.kind==="wall"&&e.level==="gf").length>4,true);
 await editor.locator("#aad-sandbox-draw").click();
 assert.equal(await editor.locator("#aad-sandbox-draw").getAttribute("aria-pressed"),"true");
 const tap1=await point(page,1.5,1),tap2=await point(page,1.5,5);
 await editor.locator("#viewer2d").click({position:{x:tap1.x,y:tap1.y}});
 await editor.locator("#viewer2d").click({position:{x:tap2.x,y:tap2.y}});
 await waitForWalls(page,afterDrag+1);
 assert((await countWalls(page))>afterDrag,"two-click creation must work on empty plan background");
 const download=page.waitForEvent("download",{timeout:12000});
 await editor.locator("#aad-save-working").click();
 const result=await download;
 assert(result.suggestedFilename().includes("AAD-SANDBOX-001"),"draft download belongs to sandbox");
 assert.deepEqual(errors,[],"Design Studio root script errors");
 await page.close();
 const mobile=await browser.newPage({viewport:{width:390,height:844},hasTouch:true,isMobile:true,deviceScaleFactor:1});
 await mobile.goto(base,{waitUntil:"networkidle",timeout:75000});
 const app=mobile.frameLocator("#ds-editor");
 await app.locator("#viewer2d").waitFor({state:"visible",timeout:60000});
 await mobile.waitForFunction(()=>document.getElementById("ds-editor")?.contentWindow?.AADStudio?.getSnapshot()?.assembly,{timeout:60000});
 assert.equal(await app.locator("#aad-sandbox-draw").getAttribute("aria-pressed"),"true");
 const mobileBefore=await countWalls(mobile);
 const a=await point(mobile,2,1.5),b=await point(mobile,6,1.5);
 await app.locator("#viewer2d").tap({position:{x:a.x,y:a.y}});
 await app.locator("#viewer2d").tap({position:{x:b.x,y:b.y}});
 await waitForWalls(mobile,mobileBefore+1);
 const over=await mobile.evaluate(()=>document.documentElement.scrollWidth-window.innerWidth);
 assert(over<=2,"mobile drawing page overflow: "+over);
 console.log("CAD_DESIGN_STUDIO_POINTER_PASS",JSON.stringify({desktopDrag:true,desktopTwoClick:true,mobileTouch:true,syntheticSourceOnly:true}));
 await mobile.close();
}finally{await browser.close();}
