import {chromium} from "playwright";
import {readFile} from "node:fs/promises";
const browser=await chromium.launch({headless:true,args:["--use-angle=swiftshader","--enable-webgl","--enable-unsafe-swiftshader"]});
const page=await browser.newPage({viewport:{width:1440,height:950},acceptDownloads:true});
const errors=[];page.on("pageerror",error=>errors.push(error.message));
try{
 await page.goto(process.env.CAD_M03_URL||"http://127.0.0.1:5174/cad/",{waitUntil:"domcontentloaded",timeout:45000});
 await page.waitForFunction(()=>document.querySelector("#status")?.textContent?.includes("M02 demo loaded"),undefined,{timeout:35000});
 if((await page.locator("#modelTree button").count())!==11)throw Error("M02 default demo regression");
 await page.locator("#newProjectId").fill("DEMO-BETA-002");
 await page.locator("#newProjectName").fill("Independent frame template B");
 await page.locator("#newProjectKind").selectOption("commercial");
 await page.locator("#newProjectLength").fill("11000");
 await page.locator("#newProjectWidth").fill("8000");
 await page.locator("#newProjectHeight").fill("3600");
 await page.locator("#createProject").click();
 await page.waitForFunction(()=>document.querySelector("#status")?.textContent?.includes("M03 new project created"));
 const title=await page.locator("#activeProject").textContent();
 if(!title?.includes("DEMO-BETA-002")||(await page.locator("#modelTree button").count())!==6)throw Error("New project did not replace demo");
 await page.locator("#modelTree button").filter({hasText:"FOOT_A"}).click();
 const original=Number(await page.locator("#x").inputValue());
 await page.locator("#x").fill(String(original+200));
 await page.locator("#elementForm button[type=submit]").click();
 await page.locator("#modelTree button").filter({hasText:"COL_A"}).click();
 const derived=Number(await page.locator("#x").inputValue());
 if(derived!==original+625)throw Error("Derived column did not inherit 200mm edit: "+derived);
 const downloadPromise=page.waitForEvent("download");
 await page.locator("#downloadProject").click();
 const download=await downloadPromise;
 if(download.suggestedFilename()!=="DEMO-BETA-002-cad-project.json")throw Error("Incorrect project package filename");
 const saved=JSON.parse(await readFile(await download.path(),"utf8"));
 if(saved.schema!=="fabin-cad://project-package/0.1"||saved.project.id!=="DEMO-BETA-002"||saved.model.elements.length!==6||saved.element_semantics.length!==6)throw Error("Missing template semantics/project envelope");
 if(saved.model.links.length!==3||saved.model.authority!=="DRAFT")throw Error("Missing project dependencies");
 await page.locator("#loadProjectFile").setInputFiles({name:"saved-project.json",mimeType:"application/json",buffer:Buffer.from(JSON.stringify(saved))});
 await page.waitForFunction(()=>document.querySelector("#status")?.textContent?.startsWith("M03 project loaded locally"));
 await page.locator("#modelTree button").filter({hasText:"COL_A"}).click();
 if(Number(await page.locator("#x").inputValue())!==derived)throw Error("Loaded project differs from saved geometry");
 const invalid=structuredClone(saved);
 invalid.model.project_id="WRONG-ID";
 await page.locator("#loadProjectFile").setInputFiles({name:"bad.json",mimeType:"application/json",buffer:Buffer.from(JSON.stringify(invalid))});
 await page.waitForFunction(()=>document.querySelector("#status")?.textContent?.startsWith("Project open rejected:"));
 if(!(await page.locator("#activeProject").textContent())?.includes("DEMO-BETA-002"))throw Error("Bad package overwrote valid project");
 if(errors.length)throw Error("Browser runtime failure "+errors.join("|"));
 console.log("CAD_M03_REUSABLE_PROJECT_E2E_PASS",{newProject:"DEMO-BETA-002",elements:6,links:3,savedAndReloaded:true,rejectedBadImport:true,errors:0});
 await page.screenshot({path:"/tmp/cad-m03-template-browser.png",fullPage:true});
}catch(err){
 console.error("CAD_M03_STATUS",await page.locator("#status").textContent().catch(()=>"(missing)"));
 console.error("CAD_M03_ERRORS",errors);
 await page.screenshot({path:"/tmp/cad-m03-template-browser.png",fullPage:true}).catch(()=>{});
 throw err;
}finally{await browser.close();}
