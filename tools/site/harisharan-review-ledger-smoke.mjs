import assert from 'node:assert/strict';
import fs from 'node:fs';
import {buildHarisharanStages} from '../../public/assets/js/harisharan-seven-stages.mjs';
import {buildReviewLedger,REVIEW_HOLDS,REVIEW_REVISION,RELEASED_SOURCE_SHA,CSV_SCHEMAS,safeCsv} from '../../public/assets/js/harisharan-review-data.mjs';
const source=JSON.parse(fs.readFileSync('public/data/projects/harisharan-adhikari/takeoff.json','utf8'));
const model=buildHarisharanStages(source);
const register=buildReviewLedger(model);
assert.equal(register.revision,REVIEW_REVISION);
assert.equal(register.issueForConstruction,false);
assert.equal(RELEASED_SOURCE_SHA,'dfd60740b7c003bc1eac581e1ac0e5c217f2fe63');
assert.deepEqual(register.stageCounts,{v02:18,v03:18,m40:18,m50:18,m60:18,m70:39,m80:0});
assert.equal(register.bars.length,178);
assert.equal(register.measurements.length,129);
assert.equal(register.boq.length,8);
assert.equal(register.totals.tankConcreteM3,null);
assert.equal(register.totals.approvedCementBags,null);
assert.equal(register.totals.approvedSteelKg,null);
assert.equal(register.totals.procurementAmountNpr,null);
assert.ok(Math.abs(register.totals.pccM3-8.029125)<0.00002,'Public per-member PCC quantities are quantized to 6 decimals; native Sheet retains 7+');
assert.ok(Math.abs(register.totals.rccM3-96.76365144)<0.001,'Native RCC has unrounded geometric values; public member snapshots have 6 decimals');
assert.ok(Math.abs(register.totals.theoreticalOwnedSteelKg-11521.11765)<0.005,'Owned bar weights use source engine quantization');
assert.ok(Math.abs(register.totals.cementPlanningBags-712.95633528)<0.05,'Per-member planning bag scenarios rounded to 3 decimals in public source');
assert.ok(REVIEW_HOLDS.find(x=>x.id==='HAR-09')?.sources.includes('ARC-02'),'Architectural sheet ID is a source reference, not inserted into narrative text');
assert.ok(REVIEW_HOLDS.find(x=>x.id==='HAR-09')?.finding.includes('septic tank'));
assert.ok(REVIEW_HOLDS.every(x=>x.issueUrl.includes('github.com/FabinGurung/JP_Computer-Aided-Drawings/issues/')));
assert.ok(register.measurements.filter(x=>x.stage==='v03').every(x=>x.concreteM3===null));
assert.ok(register.measurements.filter(x=>x.stage==='m40').every(x=>x.steelKg===null));
assert.ok(register.measurements.filter(x=>x.stage==='m50').every(x=>x.steelKg===null&&x.concreteM3===null&&x.cementPlanningBags===null));
assert.ok(register.measurements.filter(x=>x.stage==='m80').length===0);
assert.equal(register.bars.filter(x=>x.stage==='v03').length,36);
assert.ok(register.bars.every(x=>!x.cutForFabricationApproved&&x.hookAndLapUnknown&&x.kg>0));
const csv=safeCsv(register.bars,CSV_SCHEMAS.bars);
assert.equal(csv.split('\r\n').length,180);
assert.match(csv,/F-A1-X/);
assert.match(csv,/NOT_A_FABRICATION_BBS/);
assert.doesNotMatch(csv,/APPROVED_FOR_CONSTRUCTION/);
assert.equal(safeCsv([{v:'=HYPERLINK("unsafe")'}],['v']).startsWith('"v"\r\n"\'=HYPERLINK'),true,'CSV formula injection protection');
const m1=buildReviewLedger(buildHarisharanStages(source,{footingMats:1}));
assert.ok(m1.totals.theoreticalOwnedSteelKg<register.totals.theoreticalOwnedSteelKg);
const t10=buildReviewLedger(buildHarisharanStages(source,{columnTieDiameter:10,columnTieSpacing:.1}));
assert.ok(t10.totals.theoreticalOwnedSteelKg>register.totals.theoreticalOwnedSteelKg);
for(const path of ['public/assets/js/harisharan-review-dashboard.mjs','public/assets/css/harisharan-review-dashboard.css','public/projects/harisharan-adhikari/review/index.html']){
 assert.ok(fs.existsSync(path),path);
}
const html=fs.readFileSync('public/projects/harisharan-adhikari/review/index.html','utf8');
assert.match(html,/NOT FOR CONSTRUCTION/);
assert.match(html,/review-2d/);
assert.match(html,/review-3d/);
assert.match(html,/review-scenarios/);
const stage=fs.readFileSync('public/assets/js/harisharan-stage-app.mjs','utf8');
assert.match(stage,/harisharan-adhikari\/review\/\?stage=/);
assert.match(stage,/ARC-02 site plan labels an underground water tank/);
console.log('HARISHARAN_R1_R4_REVIEW_STATIC_PASS evidence='+REVIEW_HOLDS.length+' members='+register.measurements.length+' bar_families='+register.bars.length+
 ' steel_kg='+register.totals.theoreticalOwnedSteelKg+' RCC_m3='+register.totals.rccM3);
