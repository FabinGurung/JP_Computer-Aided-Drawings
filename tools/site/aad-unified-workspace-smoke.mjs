import fs from "node:fs";
import path from "node:path";
import assert from "node:assert/strict";
import {createAADWorkspace} from "../../public/assets/js/aad-unified-workspace.mjs";
import {writeIFC4,checkIfcReferences} from "../../public/assets/js/aad-building-ifc4.mjs";
const dir="public/data/projects/narayani-parajuli";
const manifest=JSON.parse(fs.readFileSync(path.join(dir,"aad-building-v1.json"),"utf8"));
const models=Object.fromEntries(manifest.levels.map(l=>[l.id,JSON.parse(fs.readFileSync(path.join(dir,l.model),"utf8"))]));
const state=createAADWorkspace(manifest,models),original=state.snapshot();
assert.equal(original.assembly.counts.wall,68);
assert.equal(original.assembly.counts.window,23);
assert.equal(original.assembly.levels.length,3);
const readOnly=state.snapshot();readOnly.models.gf.floorGraph.walls[0].thickness=99;
readOnly.assembly.elements.find(e=>e.kind==="wall").dz=99;
readOnly.manifest.levels[0].sourceArea=999;
assert.equal(state.snapshot().models.gf.floorGraph.walls[0].thickness,.23,"Snapshots must not mutate validated models");
assert.equal(state.snapshot().assembly.elements.find(e=>e.kind==="wall").dz,.23,"Snapshots must not mutate IFC geometry");
assert.equal(state.snapshot().manifest.levels[0].sourceArea,205.16,"Snapshots cannot overwrite source area authority");

const wallId=manifest.projectId+":gf:EXT-01";
const w0=original.assembly.elements.find(e=>e.id===wallId);
assert.equal(w0.dz,.23);
const changed=state.change("gf",{kind:"wall",id:"EXT-01"},{thickness:.33});
assert.equal(changed.assembly.elements.find(e=>e.id===wallId).dz,.33);
assert.equal(changed.models.gf.floorGraph.walls[0].thickness,.33);
assert.equal(changed.assembly.counts.wall,68);
const winId=manifest.projectId+":gf:WIN01";
const win0=changed.assembly.elements.find(e=>e.id===winId);
const win1=state.change("gf",{kind:"opening",id:"WIN01"},{width:1.65});
assert.equal(win1.assembly.elements.find(e=>e.id===winId).dx,1.65);
assert.notEqual(win0.x,win1.assembly.elements.find(e=>e.id===winId).x);
const node=state.change("gf",{kind:"node",id:"N19"},{x:10.03});
assert.equal(node.models.gf.floorGraph.nodes.find(n=>n.id==="N19").x,10.03);
assert.notEqual(node.assembly.elements.find(e=>e.id===manifest.projectId+":gf:PART-PORCH-W").x,
 original.assembly.elements.find(e=>e.id===manifest.projectId+":gf:PART-PORCH-W").x);
const beforeRejected=JSON.stringify(state.bundle().models);
assert.throws(()=>state.change("gf",{kind:"opening",id:"WIN01"},{width:70}),/must be|conflicts/);
assert.equal(JSON.stringify(state.bundle().models),beforeRejected,"Invalid changes must roll back atomically");
const file=writeIFC4(state.snapshot().assembly);
const parse=checkIfcReferences(file.text);
assert.equal(file.counts.IfcWindow,23);
assert.equal(file.counts.IfcWall,68);
assert.equal(parse.counts.IFCRELFILLSELEMENT,43);
const another=createAADWorkspace(manifest,models);
another.restore(state.bundle());
assert.equal(another.snapshot().models.gf.floorGraph.walls[0].thickness,.33);
assert.equal(another.snapshot().models.gf.floorGraph.openings[0].width,1.65);
assert.equal(another.snapshot().assembly.counts.wall,68);
assert.equal(another.snapshot().assembly.area.model,original.assembly.area.model);
assert.throws(()=>another.restore({...state.bundle(),projectId:"WRONG"}),/same-project/);
another.reset();
assert.equal(another.snapshot().models.gf.floorGraph.walls[0].thickness,.23);
assert.equal(another.snapshot().models.gf.floorGraph.openings[0].width,1.45);
assert.equal(another.snapshot().assembly.area.model,original.assembly.area.model);
const source=fs.readFileSync("public/projects/narayani-parajuli/aad/index.html","utf8");
assert.equal((source.match(/<iframe\b/g)||[]).length,1,"Only ONE editor iframe belongs in the project workspace");
assert.match(source,/id="aad-unified-engine"/);
assert.doesNotMatch(source,/id="aad-engine"/);
assert.doesNotMatch(source,/id="aad-multistorey-engine"/);
const common=fs.readFileSync("cad/aad/multistorey/index.html","utf8");
assert.match(common,/id="viewer2d"/);
assert.match(common,/id="viewer3d"/);
assert.match(common,/id="aad-storey"/);
assert.match(common,/id="aad-apply-edit"/);
assert.match(common,/id="aad-save-working"/);
assert.match(common,/id="elements"/);
console.log("AAD_UNIFIED_SINGLE_STATE_PASS",JSON.stringify({originalWalls:68,windows:23,levels:3,editedThickness:.33,editedWidth:1.65,ifcTypes:parse.counts.IFCBUILDINGSTOREY}));
