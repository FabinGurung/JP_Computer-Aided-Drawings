import fs from 'node:fs';
import assert from 'node:assert/strict';
import {assembly,calculate} from '../../public/assets/js/harisharan-takeoff.mjs';
import {REAR_NINE_CANDIDATE,ALTERNATE_NINE_CANDIDATE,draftDefaults,validateDraft,scopeMemberGraph,scopeCalculation} from '../../public/assets/js/harisharan-rear-nine.mjs';
import {packageRecords} from '../../public/assets/js/project-site-packages.mjs';
const source=JSON.parse(fs.readFileSync('public/data/projects/harisharan-adhikari/takeoff.json','utf8'));
const main=fs.readFileSync('public/projects/harisharan-adhikari/rear-nine/main.mjs','utf8');
const html=fs.readFileSync('public/projects/harisharan-adhikari/rear-nine/index.html','utf8');
const nodes=assembly(source).nodes;
assert.equal(nodes.length,18);
assert.equal(REAR_NINE_CANDIDATE.length,9);
assert.equal(new Set(REAR_NINE_CANDIDATE).size,9);
assert.deepEqual(REAR_NINE_CANDIDATE,['A4','B4','E4','A5','B5','D5','A6','B6','C6']);
assert.equal(new Set(ALTERNATE_NINE_CANDIDATE).size,9);
const selected=nodes.filter(n=>REAR_NINE_CANDIDATE.includes(n.id));
assert.equal(selected.length,9);
assert.deepEqual(selected.map(n=>n.row).sort(),[4,4,4,5,5,5,6,6,6]);
assert.equal(selected.filter(n=>n.footing==='F1').length,3);
assert.equal(selected.filter(n=>n.footing==='F2').length,6);
assert.equal(selected.find(n=>n.id==='B4').type,'C1');
assert.equal(selected.find(n=>n.id==='B5').type,'C2');
assert.equal(selected.filter(n=>n.type==='C4').length,2);
const draft=draftDefaults(source);
assert.equal(draft.approvedByEngineer,false);
assert.equal(draft.reviewer,null);
assert.deepEqual(validateDraft(draft,source).selectedNodeIds,draft.selectedNodeIds);
const result=scopeCalculation(source,draft);
assert.deepEqual(result.scope,{columns:9,footings:9,strapBeams:6,plinthInternal:12,plinthBoundary:3,plinthTotal:15});
assert.ok(Math.abs(result.volumes.footingEnvelopeM3-32.1165)<.000001);
assert.ok(Math.abs(result.volumes.pccPadOnlyM3-4.0145625)<.000001);
assert.ok(Math.abs(result.volumes.columnM3-2.642625)<.000001);
assert.ok(result.steelKg>0&&result.steelKg<calculate(source).totalSteel);
assert.equal(result.cementScenarioBags,null);
assert.equal(result.qa.constructionRelease,'NOT_ISSUED');
assert.ok(result.rows.some(r=>r.id==='C-B4-25'&&r.count===6&&r.diameter===25));
assert.ok(result.rows.some(r=>r.id==='CT-B4'&&r.diameter===8));
assert.ok(result.rows.some(r=>r.id==='ST-B4-E4-20'));
assert.ok(result.rows.some(r=>r.id==='PB-B3-B4-20'));
assert.ok(!result.rows.some(r=>r.id==='F-A1-X'));
assert.equal(result.rows.length,new Set(result.rows.map(r=>r.id)).size);
const noBoundary=scopeCalculation(source,{...draft,includeBoundaryPlinth:false});
assert.equal(noBoundary.scope.plinthTotal,12);
assert.ok(noBoundary.steelKg<result.steelKg);
assert.ok(noBoundary.volumes.rccScenarioM3<result.volumes.rccScenarioM3);
const alt=scopeCalculation(source,{...draft,selectedNodeIds:[...ALTERNATE_NINE_CANDIDATE],overrides:{}});
assert.equal(alt.scope.columns,9);
assert.equal(alt.scope.strapBeams,6);
assert.ok(!alt.rows.some(r=>r.id==='F-A6-X'));
const baseRow=result.rows.find(r=>r.id==='F-A4-X');
const updated=scopeCalculation(source,{...draft,overrides:{'F-A4-X':{count:baseRow.count+1}}});
assert.ok(updated.steelKg>result.steelKg);
assert.ok(updated.rows.find(r=>r.id==='F-A4-X').edited);
assert.equal(calculate(source).steel.find(r=>r.id==='F-A4-X').count,baseRow.count);
assert.throws(()=>validateDraft({...draft,selectedNodeIds:['A4']},source),/exactly nine/);
assert.throws(()=>validateDraft({...draft,approvedByEngineer:true},source),/cannot claim approval/);
assert.throws(()=>validateDraft({...draft,sourceFileSha256:'fake'},source),/source hash mismatch/);
assert.throws(()=>validateDraft({...draft,overrides:{'F-A1-X':{count:33}}},source),/bar outside/);
assert.match(html,/NOT FOR CONSTRUCTION/);
assert.match(main,/localStorage/);
assert.match(main,/Export draft JSON/);
assert.match(main,/rear orientation|Rear orientation/i);
assert.match(main,/HAR-01|source\.issues/);
const cards=packageRecords('harisharan-adhikari');
assert.equal(cards.length,7);
const card=cards.find(c=>c.id==='rear-nine');
assert.ok(card);
assert.match(card.status,/DRAFT/);
assert.equal(card.verified,false);
assert.ok(fs.existsSync('public/projects/harisharan-adhikari/rear-nine/index.html'));
assert.ok(fs.existsSync('public/projects/harisharan-adhikari/rear-nine/main.mjs'));
console.log('HARISHARAN_REAR_NINE_CONTRACT_PASS: 9 pads + 9 columns, 6 straps, 12 internal + 3 boundary plinth, drafts not approvals');
